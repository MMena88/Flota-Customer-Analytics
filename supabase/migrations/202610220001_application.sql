CREATE TABLE "fleet_transactions" (
	"version_id" text PRIMARY KEY NOT NULL,
	"transaction_id" text NOT NULL,
	"import_id" text NOT NULL,
	"content_hash" text NOT NULL,
	"account" text NOT NULL,
	"date" text NOT NULL,
	"time" text NOT NULL,
	"status" text NOT NULL,
