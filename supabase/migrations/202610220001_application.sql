	"amount_cents" bigint NOT NULL,
	"authorised_volume_milli" bigint,
	"authorised_amount_cents" bigint,
	"odometer" text DEFAULT '' NOT NULL,
	"card_last4" text DEFAULT '' NOT NULL,
	"reference" text DEFAULT '' NOT NULL,
